export function manifestStateHash(state: string): string {
  return createHash('sha256').update(state).digest('hex');
}

export function externalUrl(input: unknown, allowLocalHttp = false): URL | null {
  if (typeof input !== 'string' || input.length > 2048) return null;
  try {
    const url = new URL(input);
    if (url.username || url.password || url.search || url.hash) return null;
    const local = url.hostname === 'localhost' || url.hostname === '127.0.0.1';
    if (url.protocol !== 'https:' && !(allowLocalHttp && local && url.protocol === 'http:'))
      return null;
    return url;
  } catch {
    return null;
  }
}

export function githubAppOwnerPath(ownerType: string, organization?: string): string | null {
  if (ownerType === 'personal') return 'https://github.com/settings/apps/new';
  if (
    ownerType !== 'organization' ||
    !organization ||
    !/^[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?$/.test(organization)
  )
    return null;
  return `https://github.com/organizations/${encodeURIComponent(organization)}/settings/apps/new`;
}

